# 2.4) Tratamiento de outliers por curso usando IQR sobre puntajes SIMCE

# El IQR se calcula por curso porque mezclar 4° básico, 6° básico, 8° básico y II medio
# puede clasificar como outlier un valor que solo pertenece a otra escala de comparación educativa.

def filtrar_outliers_iqr_por_curso(df_in, targets_modelo):
    keep_global = pd.Series(True, index=df_in.index)
    filas_resumen = []

    for curso, g in df_in.groupby("curso"):
        keep_curso = pd.Series(True, index=g.index)
        for col in targets_modelo:
            q1 = g[col].quantile(0.25)
            q3 = g[col].quantile(0.75)
            iqr = q3 - q1
            lower = q1 - 1.5 * iqr
            upper = q3 + 1.5 * iqr
            keep_col = g[col].between(lower, upper)
            filas_resumen.append({
                "curso": curso,
                "curso_nombre": CURSO_NOMBRE.get(curso, curso),
                "variable": col,
                "limite_inferior": lower,
                "limite_superior": upper,
                "outliers_detectados": int((~keep_col).sum()),
            })
            keep_curso &= keep_col
        keep_global.loc[g.index] = keep_curso

    return df_in.loc[keep_global].copy(), pd.DataFrame(filas_resumen)


