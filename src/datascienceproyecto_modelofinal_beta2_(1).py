def calcular_vif_sklearn(df_num):
    """Calcula VIF sin depender de statsmodels."""
    from sklearn.linear_model import LinearRegression

    filas = []
    for col in df_num.columns:
        y = df_num[col].values
        X = df_num.drop(columns=[col]).values
        r2 = LinearRegression().fit(X, y).score(X, y)
        vif = np.inf if (1 - r2) <= 1e-12 else 1 / (1 - r2)
        filas.append({"variable": col, "indicador": IDPS_NOMBRE.get(col, col), "R2_auxiliar": r2, "VIF": vif})
