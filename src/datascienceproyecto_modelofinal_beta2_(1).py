        pipe = crear_pipeline_pred(feat_num, FEAT_CAT_PRED)
        pipe.fit(train_pred[feat_num + FEAT_CAT_PRED], train_pred[target])
        m_tr = calcular_metricas(train_pred[target], pipe.predict(train_pred[feat_num + FEAT_CAT_PRED]))
