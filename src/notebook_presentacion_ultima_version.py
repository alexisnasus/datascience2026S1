# 4.8) Entrenamiento del modelo Ridge sin NSE

features_num_sin_nse = ["ind_am", "ind_cc", "ind_hv", "ind_pf"]
features_cat_sin_nse = ["cod_rural_rbd", "cod_depe2"]
features_modelo_sin_nse = features_num_sin_nse + features_cat_sin_nse


def crear_pipeline_regresion_sin_nse():
    preprocessor = ColumnTransformer(transformers=[
        ("num", StandardScaler(), features_num_sin_nse),
        ("cat", OneHotEncoder(handle_unknown="ignore", drop="first"), features_cat_sin_nse),
    ])

    return Pipeline(steps=[
        ("preprocessor", preprocessor),
        ("regressor", RidgeCV(alphas=ALPHAS_RIDGE, cv=5)),
    ])


def obtener_feature_names_sin_nse(model):
    pre = model.named_steps["preprocessor"]
    num_names = pre.named_transformers_["num"].get_feature_names_out(features_num_sin_nse).tolist()
    cat_names = pre.named_transformers_["cat"].get_feature_names_out(features_cat_sin_nse).tolist()
    return num_names + cat_names


def entrenar_modelo_sin_nse(df_curso, curso, target, asignatura):
    data = df_curso.dropna(subset=features_modelo_sin_nse + [target, "rbd"]).copy()

    X = data[features_modelo_sin_nse]
    y = data[target]
    groups = data["rbd"]

    model = crear_pipeline_regresion_sin_nse()

    splitter = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
    train_idx, test_idx = next(splitter.split(X, y, groups=groups))

    X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
    y_train, y_test = y.iloc[train_idx], y.iloc[test_idx]

    model.fit(X_train, y_train)

    alpha_seleccionado = model.named_steps["regressor"].alpha_

    y_pred_train = model.predict(X_train)
    y_pred_test = model.predict(X_test)

    metricas_train = calcular_metricas(y_train, y_pred_train)
    metricas_test = calcular_metricas(y_test, y_pred_test)

    cv_metricas = {"MAE_CV": np.nan, "RMSE_CV": np.nan, "R2_CV": np.nan, "R2_CV_STD": np.nan}
    n_groups = groups.nunique()
    if n_groups >= 3:
        cv = GroupKFold(n_splits=min(5, n_groups))
        scoring = {
            "MAE": "neg_mean_absolute_error",
            "MSE": "neg_mean_squared_error",
            "R2": "r2",
        }
        cv_scores = cross_validate(
            crear_pipeline_regresion_sin_nse(), X, y,
            groups=groups, cv=cv, scoring=scoring,
            return_train_score=False,
        )
        cv_metricas = {
            "MAE_CV": -cv_scores["test_MAE"].mean(),
            "RMSE_CV": np.sqrt(-cv_scores["test_MSE"]).mean(),
            "R2_CV": cv_scores["test_R2"].mean(),
            "R2_CV_STD": cv_scores["test_R2"].std(),
        }

    feature_names = obtener_feature_names_sin_nse(model)
    coefs = model.named_steps["regressor"].coef_
    coef_df = pd.DataFrame({
        "variable": feature_names,
        "coeficiente": coefs,
    }).sort_values("coeficiente", key=lambda s: s.abs(), ascending=False)

    pred_df = pd.DataFrame({
        "curso": curso,
        "curso_nombre": CURSO_NOMBRE[curso],
        "asignatura": asignatura,
        "real": y_test.values,
        "predicho": y_pred_test,
    })
    pred_df["residuo"] = pred_df["real"] - pred_df["predicho"]

    metricas = {
        "curso": curso,
        "curso_nombre": CURSO_NOMBRE[curso],
        "asignatura": asignatura,
        "n_total": len(data),
        "n_train": len(X_train),
        "n_test": len(X_test),
        "alpha_seleccionado": alpha_seleccionado,
        "MAE_train": metricas_train["MAE"],
        "RMSE_train": metricas_train["RMSE"],
        "R2_train": metricas_train["R2"],
        "MAE_test": metricas_test["MAE"],
        "RMSE_test": metricas_test["RMSE"],
        "R2_test": metricas_test["R2"],
        **cv_metricas,
    }

    return {
        "model": model,
        "metricas": metricas,
        "coeficientes": coef_df,
        "predicciones": pred_df,
    }


