"""---
# 4) MODEL: Ridge Regression por curso y asignatura

Se entrenan **8 modelos**, exactamente igual que en el modelo OLS:

- 4 cursos: 4° básico, 6° básico, 8° básico y II medio.
- 2 asignaturas: Matemática y Lectura.

La estructura, el preprocesamiento, el split y la validación cruzada son **idénticos al modelo de regresión lineal múltiple**. La única diferencia es el regresor: `RidgeCV` en lugar de `LinearRegression`.

## Pipeline y validación (igual que en OLS)

- **Split agrupado por `rbd`:** evita que un mismo establecimiento aparezca simultáneamente en entrenamiento y prueba.
- **Validación cruzada agrupada:** evalúa estabilidad respetando la unidad establecimiento.
- **NSE ordinal estandarizado:** permite comparar su magnitud con los IDPS.
- **One-hot con categoría base (`drop="first"`):** evita redundancia perfecta entre categorías y facilita la interpretación de las variables contextuales.

## Diferencia específica de Ridge

- El regresor es `RidgeCV(alphas=ALPHAS_RIDGE, cv=5)`, que selecciona automáticamente el parámetro de penalización `alpha` para **cada uno de los 8 modelos** (cada combinación de curso y asignatura puede tener un `alpha` distinto).
- Ridge **no elimina variables**: encoge (shrinkage) los coeficientes hacia cero, lo que reduce su varianza cuando hay multicolinealidad entre los IDPS, pero mantiene todas las variables del modelo.
- La interpretación de los coeficientes es la misma que en OLS (asociaciones ajustadas, manteniendo constantes las demás variables), pero los valores absolutos de los coeficientes de Ridge suelen ser algo menores que los de OLS.

## Variables del modelo (idénticas a OLS)

**Targets:**

- `prom_mate2m_rbd`: puntaje SIMCE Matemática.
- `prom_lect2m_rbd`: puntaje SIMCE Lectura.

**Predictores:**

- IDPS: `ind_am`, `ind_cc`, `ind_hv`, `ind_pf`.
- NSE ordinal estandarizado: `nse_ord`.
- Ruralidad: `cod_rural_rbd`.
- Dependencia administrativa: `cod_depe2`.

La variable `curso` no se usa como predictor dentro de cada modelo porque cada modelo se ajusta sobre un único curso.
"""

# 4.1) Funciones de modelamiento (Ridge)

features_num = ["ind_am", "ind_cc", "ind_hv", "ind_pf", "nse_ord"]
features_cat = ["cod_rural_rbd", "cod_depe2"]
features_modelo = features_num + features_cat


def calcular_metricas(y_real, y_estimado):
    return {
        "MAE": mean_absolute_error(y_real, y_estimado),
        "RMSE": np.sqrt(mean_squared_error(y_real, y_estimado)),
        "R2": r2_score(y_real, y_estimado),
    }


def crear_pipeline_regresion():
    preprocessor = ColumnTransformer(transformers=[
        ("num", StandardScaler(), features_num),
        ("cat", OneHotEncoder(handle_unknown="ignore", drop="first"), features_cat),
    ])

    return Pipeline(steps=[
        ("preprocessor", preprocessor),
        ("regressor", RidgeCV(alphas=ALPHAS_RIDGE, cv=5)),
    ])


def obtener_feature_names(model):
    pre = model.named_steps["preprocessor"]
    num_names = pre.named_transformers_["num"].get_feature_names_out(features_num).tolist()
    cat_names = pre.named_transformers_["cat"].get_feature_names_out(features_cat).tolist()
    return num_names + cat_names


def entrenar_modelo(df_curso, curso, target, asignatura):
    data = df_curso.dropna(subset=features_modelo + [target, "rbd"]).copy()

    X = data[features_modelo]
    y = data[target]
    groups = data["rbd"]

    model = crear_pipeline_regresion()

    # Split agrupado por establecimiento para evitar que el mismo RBD quede simultáneamente en train y test.
    if groups.nunique() >= 5:
        splitter = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
        train_idx, test_idx = next(splitter.split(X, y, groups=groups))
    else:
        # Fallback poco probable: si hubiese muy pocos establecimientos.
        rng = np.random.default_rng(42)
        indices = np.arange(len(data))
        rng.shuffle(indices)
        split = int(len(indices) * 0.8)
        train_idx, test_idx = indices[:split], indices[split:]

    X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
    y_train, y_test = y.iloc[train_idx], y.iloc[test_idx]

    model.fit(X_train, y_train)

    # Alpha seleccionado automáticamente por RidgeCV para este curso/asignatura.
    alpha_seleccionado = model.named_steps["regressor"].alpha_

    y_pred_train = model.predict(X_train)
    y_pred_test = model.predict(X_test)

    metricas_train = calcular_metricas(y_train, y_pred_train)
    metricas_test = calcular_metricas(y_test, y_pred_test)

    # Validación cruzada agrupada por RBD en el set completo del curso/asignatura.
    cv_metricas = {"MAE_CV": np.nan, "RMSE_CV": np.nan, "R2_CV": np.nan, "R2_CV_STD": np.nan}
    n_groups = groups.nunique()
    if n_groups >= 3:
        cv = GroupKFold(n_splits=min(5, n_groups))
        scoring = {
            "MAE": "neg_mean_absolute_error",
            "MSE": "neg_mean_squared_error",
            "R2": "r2",
        }
        cv_scores = cross_validate(
            crear_pipeline_regresion(), X, y,
            groups=groups, cv=cv, scoring=scoring,
            return_train_score=False,
        )
        cv_metricas = {
            "MAE_CV": -cv_scores["test_MAE"].mean(),
            "RMSE_CV": np.sqrt(-cv_scores["test_MSE"]).mean(),
            "R2_CV": cv_scores["test_R2"].mean(),
            "R2_CV_STD": cv_scores["test_R2"].std(),
        }

    feature_names = obtener_feature_names(model)
    coefs = model.named_steps["regressor"].coef_
    coef_df = pd.DataFrame({
        "variable": feature_names,
        "coeficiente": coefs,
    }).sort_values("coeficiente", key=lambda s: s.abs(), ascending=False)

    pred_df = pd.DataFrame({
        "curso": curso,
        "curso_nombre": CURSO_NOMBRE[curso],
        "asignatura": asignatura,
        "real": y_test.values,
        "predicho": y_pred_test,
    })
    pred_df["residuo"] = pred_df["real"] - pred_df["predicho"]

    metricas = {
        "curso": curso,
        "curso_nombre": CURSO_NOMBRE[curso],
        "asignatura": asignatura,
        "n_total": len(data),
        "n_train": len(X_train),
        "n_test": len(X_test),
        "alpha_seleccionado": alpha_seleccionado,
        "MAE_train": metricas_train["MAE"],
        "RMSE_train": metricas_train["RMSE"],
        "R2_train": metricas_train["R2"],
        "MAE_test": metricas_test["MAE"],
        "RMSE_test": metricas_test["RMSE"],
        "R2_test": metricas_test["R2"],
        **cv_metricas,
    }

    return {
        "model": model,
        "metricas": metricas,
        "coeficientes": coef_df,
        "predicciones": pred_df,
    }

